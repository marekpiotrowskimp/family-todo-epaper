#!/bin/sh
# Writes ios/Local.xcconfig (ignored by git) with your Apple development team and,
# optionally, your own bundle identifier, then regenerates the Xcode project.
#
# Usage: tools/setup-ios-signing.sh TEAM_ID [BUNDLE_ID]
#   TEAM_ID    10-character Apple team ID (Xcode → Settings → Accounts, or developer.apple.com → Membership)
#   BUNDLE_ID  e.g. com.yourname.familytodo — required unless you are the original author,
#              because bundle identifiers are unique across all Apple developer teams
set -eu
cd "$(dirname "$0")/.."

[ $# -ge 1 ] || { sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }
team=$1
bundle=${2:-}

{
  echo "// Generated by tools/setup-ios-signing.sh. Do not commit."
  echo "DEVELOPMENT_TEAM = $team"
  [ -z "$bundle" ] || echo "PRODUCT_BUNDLE_IDENTIFIER = $bundle"
} > ios/Local.xcconfig
echo "Wrote ios/Local.xcconfig"

if command -v xcodegen >/dev/null; then
  xcodegen generate --spec ios/project.yml
else
  echo "xcodegen not found (brew install xcodegen) — the committed ios/FamilyTodo.xcodeproj also works."
fi
