#!/bin/sh
# Generates the shared family key for the firmware and shows it for the iOS app.
#
#   include/family_key.h   (ESP32 firmware, ignored by git) — compiled into the display
#   iOS app                — scan the printed QR code with the iPhone camera, or paste the
#                            link / 64-character key on the app's Welcome or Settings screen.
#                            The app keeps it in the Keychain; it is never compiled in.
#
# Usage:
#   tools/make-family-key.sh           create the key (refuses to overwrite an existing one)
#   tools/make-family-key.sh --force   create a new key (re-flash the firmware, re-enter it on every phone)
#   tools/make-family-key.sh --show    print the link / QR code of the existing key again
#
# The QR code is printed in the terminal when `qrencode` is installed (brew install qrencode).
set -eu
cd "$(dirname "$0")/.."

H=include/family_key.h

show() {
  [ -f "$H" ] || { echo "Missing $H — run tools/make-family-key.sh" >&2; exit 1; }
  hex=$(grep -o '0x[0-9a-fA-F][0-9a-fA-F]' "$H" | sed 's/0x//' | tr -d '\n' | tr 'A-F' 'a-f')
  [ ${#hex} -eq 64 ] || { echo "$H does not contain a 32-byte key" >&2; exit 1; }
  link="familytodo://key?k=$hex"
  echo
  echo "Add the key to the iOS app (once per phone):"
  if command -v qrencode >/dev/null; then
    echo "  scan this QR code with the iPhone camera and tap \"Open in To-Do\":"
    echo
    qrencode -t ANSIUTF8 -m 2 "$link"
  else
    echo "  (install qrencode — brew install qrencode — to get a QR code to scan)"
  fi
  echo "  or paste on the Welcome / Settings screen:"
  echo "  $link"
  echo
  echo "Keep it private: anyone with the key can read and change your family's tasks."
}

case "${1:-}" in
  --show) show; exit 0 ;;
  --force|"") ;;
  *) echo "Unknown option: $1 (use --force or --show)" >&2; exit 2 ;;
esac

if [ "${1:-}" != "--force" ] && [ -e "$H" ]; then
  echo "A key already exists. Use --show to display it, or --force to generate a new one" >&2
  echo "(then re-flash the firmware and enter the new key on every phone)." >&2
  exit 1
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }
bytes=$(openssl rand -hex 32 | sed 's/../0x&, /g; s/, $//')

umask 077
cat > "$H" <<EOF
// Generated by tools/make-family-key.sh. Do not commit.
#pragma once

#include <cstdint>

static const uint8_t FAMILY_KEY[32] = {$bytes};
EOF

echo "Wrote $H."
show
