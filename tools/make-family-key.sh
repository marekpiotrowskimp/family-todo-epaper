#!/bin/sh
# Generates the shared family key and writes it to two files that git ignores:
#   include/family_key.h            (ESP32 firmware)
#   ios/FamilyTodo/FamilyKey.swift  (iOS app)
# Both files must hold the same key, otherwise the app is rejected by the display (bad_mac).
#
# Usage:
#   tools/make-family-key.sh           create the key (refuses to overwrite an existing one)
#   tools/make-family-key.sh --force   create a new key (re-flash the firmware and rebuild the app)
#   tools/make-family-key.sh --check   verify that both files exist and hold the same key
set -eu
cd "$(dirname "$0")/.."

H=include/family_key.h
S=ios/FamilyTodo/FamilyKey.swift

key_bytes() { # prints the 32 key bytes of a file as lowercase hex, one per line
  grep -o '0x[0-9a-fA-F][0-9a-fA-F]' "$1" | tr 'A-F' 'a-f'
}

case "${1:-}" in
  --check)
    for f in "$H" "$S"; do
      [ -f "$f" ] || { echo "Missing $f — run tools/make-family-key.sh" >&2; exit 1; }
    done
    [ "$(key_bytes "$H" | wc -l | tr -d ' ')" = 32 ] || { echo "$H does not contain 32 key bytes" >&2; exit 1; }
    if [ "$(key_bytes "$H")" = "$(key_bytes "$S")" ]; then
      echo "OK: $H and $S hold the same key."
    else
      echo "Key mismatch between $H and $S — run tools/make-family-key.sh --force" >&2; exit 1
    fi
    exit 0 ;;
  --force|"") ;;
  *) echo "Unknown option: $1 (use --force or --check)" >&2; exit 2 ;;
esac

if [ "${1:-}" != "--force" ] && { [ -e "$H" ] || [ -e "$S" ]; }; then
  echo "A key already exists. Use --force to generate a new one (then re-flash the firmware and rebuild the app)." >&2
  exit 1
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }
hex=$(openssl rand -hex 32)
bytes=$(echo "$hex" | sed 's/../0x&, /g; s/, $//')

umask 077
cat > "$H" <<EOF
// Generated by tools/make-family-key.sh. Do not commit.
#pragma once

#include <cstdint>

static const uint8_t FAMILY_KEY[32] = {$bytes};
EOF

cat > "$S" <<EOF
// Generated by tools/make-family-key.sh. Do not commit.
import Foundation

enum FamilyKey {
    static let secret = Data([$bytes])
}
EOF

echo "Wrote $H and $S (same key). Keep them private — anyone with the key can edit your tasks."
