static const PriorityIcon kHigh = {kPriorityIconSize, kPriorityIconSize, kFlagFilled};
static const PriorityIcon kNormal = {kPriorityIconSize, kPriorityIconSize, kFlagOutline};
static const PriorityIcon kLow = {kPriorityIconSize, kPriorityIconSize, kDash};

const PriorityIcon& priorityIcon(Priority p) {
  switch (p) {
    case Priority::High: return kHigh;
    case Priority::Normal: return kNormal;
    case Priority::Low: break;
  }
  return kLow;
}

bool iconPixel(const PriorityIcon& icon, int16_t x, int16_t y) {
  if (icon.bits == nullptr || x < 0 || y < 0 || x >= icon.width || y >= icon.height) return false;
  return (icon.bits[y * kPriorityIconRowBytes + x / 8] & (0x80 >> (x % 8))) != 0;
}

